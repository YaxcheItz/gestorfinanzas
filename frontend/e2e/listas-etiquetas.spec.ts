import { expect, test } from '@playwright/test';
import { registrarPrueba } from './registro-helper';
test.use({viewport:{width:390,height:844},hasTouch:true,serviceWorkers:'block'});
test.setTimeout(180_000);
test('listas separan movimientos, conservan etiquetas y comparten con permisos reales',async({page})=>{
  const email=`listas-${crypto.randomUUID()}@example.test`,password='Password123';
  const registro=await registrarPrueba(page.request,{nombre:'QA Listas',email,password});expect(registro.ok()).toBeTruthy();
  const headers={Authorization:`Bearer ${(await registro.json()).data.token}`};
  const cuentaR=await page.request.post('/api/cuentas',{headers,data:{nombre:'Banco Viaje',tipo:'DEBITO',moneda:'MXN',saldoInicial:1000}});expect(cuentaR.ok()).toBeTruthy();
  const cuentaId=(await cuentaR.json()).data.id;
  await page.goto('/login');await page.locator('#email').fill(email);await page.locator('#password').fill(password);
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await expect(page).toHaveURL(/dashboard/);
  await page.getByRole('button',{name:'Cambiar lista',exact:true}).click();
  const listas=page.getByRole('dialog',{name:'Tus listas',exact:true});await expect(listas).toBeVisible();
  await listas.getByRole('button',{name:/Nueva lista/}).click();
  await page.getByLabel('Nombre de la lista',{exact:true}).fill('Vacaciones');
  await page.getByRole('button',{name:'Guardar lista',exact:true}).click();
  await expect(page.getByRole('button',{name:'Cambiar a Vacaciones',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cambiar a Vacaciones',exact:true}).click();
  await expect(page.getByRole('button',{name:'Cambiar lista',exact:true})).toContainText('Vacaciones');
  await page.getByRole('button',{name:'Añadir movimiento',exact:true}).click();
  const entrada=page.getByRole('dialog',{name:'Añadir movimiento',exact:true});
  await entrada.locator('select[name="cuenta"]').selectOption({label:'Banco Viaje · MXN'});
  await page.locator('#quick-entry-amount').fill('25');await entrada.locator('summary').click();
  await entrada.locator('input[name="descripcion"]').fill('Cena del viaje');
  await entrada.locator('input[name="etiquetasMovimiento"]').fill('#viaje #visa');
  await entrada.getByRole('button',{name:'Guardar gasto',exact:true}).click();await expect(entrada).not.toBeVisible();
  await page.getByRole('link',{name:'Movimientos',exact:true}).click();
  const search=page.getByRole('searchbox',{name:'Buscar movimientos'});await search.fill('#visa');
  await expect(page.locator('app-movimiento-mobile-card')).toHaveCount(1);
  await expect(page.locator('app-movimiento-mobile-card')).toContainText('Cena del viaje');
  await expect(page.locator('app-movimiento-mobile-card')).toContainText('#visa');
  const todos=await page.request.get('/api/listas',{headers});expect(todos.ok()).toBeTruthy();
  const lista=(await todos.json()).data.find((l:{nombre:string})=>l.nombre==='Vacaciones');expect(lista).toBeTruthy();
  const invitacion=await page.request.post(`/api/listas/${lista.id}/invitacion`,{headers,data:{rol:'LECTOR'}});expect(invitacion.ok()).toBeTruthy();
  const otro=await registrarPrueba(page.request,{nombre:'QA Lector',email:`lector-${crypto.randomUUID()}@example.test`,password});expect(otro.ok()).toBeTruthy();
  const otroHeaders={Authorization:`Bearer ${(await otro.json()).data.token}`};
  const denegado=await page.request.get(`/api/transacciones?listaId=${lista.id}`,{headers:otroHeaders});expect(denegado.status()).toBe(403);
  const union=await page.request.post('/api/listas/unirse',{headers:otroHeaders,data:{codigo:(await invitacion.json()).data.codigo}});expect(union.ok()).toBeTruthy();
  const compartidos=await page.request.get(`/api/transacciones?listaId=${lista.id}&busqueda=%23visa`,{headers:otroHeaders});expect(compartidos.ok()).toBeTruthy();expect((await compartidos.json()).data.totalElements).toBe(1);
  await page.getByRole('button',{name:'Cambiar lista',exact:true}).click();await page.getByRole('button',{name:'Cambiar a Personal',exact:true}).click();
  await expect(page.locator('app-movimiento-mobile-card').filter({hasText:'Cena del viaje'})).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.reload();await expect(page.getByRole('button',{name:'Cambiar lista',exact:true})).toContainText('Personal');
  await expect(page.locator('app-movimiento-mobile-card').filter({hasText:'Cena del viaje'})).toHaveCount(0);
  await page.goto(`/transacciones?listaId=${lista.id}`);
  await expect(page.getByRole('button',{name:'Cambiar lista',exact:true})).toContainText('Vacaciones');
  await expect(page.locator('app-movimiento-mobile-card').filter({hasText:'Cena del viaje'})).toHaveCount(1);

});
