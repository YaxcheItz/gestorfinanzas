import {expect,test} from '@playwright/test';
import {registrarPrueba} from './registro-helper';

test.use({viewport:{width:390,height:844},hasTouch:true,serviceWorkers:'block'});
test.setTimeout(60_000);
test('historial permite buscar, filtrar y revisar movimientos sin perder controles en móvil',async({page},testInfo)=>{
  await page.context().setOffline(false);
  const email=`historial-${crypto.randomUUID()}@example.test`,password='Password123';
  const registro=await registrarPrueba(page.request,{nombre:'QA historial',email,password});
  expect(registro.ok()).toBeTruthy();
  const headers={Authorization:`Bearer ${(await registro.json()).data.token}`};
  const cuenta=await page.request.post('/api/cuentas',{headers,data:{nombre:'Banco de prueba',tipo:'DEBITO',moneda:'MXN',saldoInicial:1000}});
  expect(cuenta.ok()).toBeTruthy();const cuentaId=(await cuenta.json()).data.id;
  const localDate=(date:Date)=>`${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`;
  const hoy=new Date(),ayer=new Date(hoy.getFullYear(),hoy.getMonth(),hoy.getDate()-1);
  const categoriasRespuesta=await page.request.get('/api/categorias',{headers});expect(categoriasRespuesta.ok()).toBeTruthy();
  const categorias=(await categoriasRespuesta.json()).data;
  for(const [tipo,monto,descripcion,fecha] of [['GASTO',25,'Tacos de prueba',localDate(hoy)],['INGRESO',100,'Nomina de prueba',localDate(ayer)]] as const){
    const categoria=categorias.find((c:{tipo:string;activo:boolean})=>c.tipo===tipo&&c.activo);expect(categoria).toBeTruthy();
    const r=await page.request.post('/api/transacciones',{headers,data:{tipo,monto,descripcion,fecha,cuentaId,categoriaId:categoria.id,notas:'Nota separada'}});expect(r.ok()).toBeTruthy();
    expect((await r.json()).data.descripcion).toBe(descripcion);
  }
  const invalida=await page.request.post('/api/transacciones',{headers,data:{tipo:'GASTO',monto:1,descripcion:'x'.repeat(201),fecha:localDate(hoy),cuentaId}});expect(invalida.status()).toBe(400);
  await page.goto('/login');await page.locator('#email').fill(email);await page.locator('#password').fill(password);
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await expect(page).toHaveURL(/dashboard/);
  await page.goto('/transacciones');
  const types=page.getByRole('group',{name:'Tipo de movimiento',exact:true}),search=page.getByRole('searchbox',{name:'Buscar movimientos'});
  await expect(page.locator('.history-day').filter({has:page.getByRole('heading',{name:/Hoy/})})).toBeVisible();
  await expect(page.locator('.history-day').filter({has:page.getByRole('heading',{name:/Ayer/})})).toBeVisible();
  const cards=page.locator('app-movimiento-mobile-card');
  await types.getByRole('button',{name:'Gastos',exact:true}).click();
  await expect(cards).toHaveCount(1);await expect(cards.first()).toContainText('Tacos de prueba');await expect(cards.first()).toContainText('Banco de prueba');
  await search.fill('Tacos');
  await expect(page.getByRole('button',{name:'Quitar filtro: Búsqueda: Tacos',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Quitar filtro: Gasto',exact:true}).click();
  await expect(search).toHaveValue('Tacos');await expect(cards).toHaveCount(1);
  await expect(types.getByRole('button',{name:'Todos',exact:true})).toHaveAttribute('aria-pressed','true');
  const taco=cards.filter({hasText:'Tacos de prueba'}).getByRole('button',{name:'Ver detalle de Tacos de prueba'});
  await taco.focus();await taco.press('Enter');
  const detail=page.getByRole('dialog',{name:'Detalle',exact:true});
  await expect(detail.locator('.ledger-detail-sheet__category')).toHaveText('Tacos de prueba');
  await detail.getByRole('button',{name:'Ocultar montos',exact:true}).click();
  await expect(detail.locator('.ledger-detail-sheet__amount')).toContainText('•••');
  await page.setViewportSize({width:320,height:568});
  await expect.poll(()=>detail.evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=-1&&r.bottom<=innerHeight+1&&r.right<=innerWidth+1;})).toBe(true);
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('detalle-privado-320.png')});
  await detail.getByRole('button',{name:'Mostrar montos',exact:true}).click();
  await expect(detail.locator('.ledger-detail-sheet__amount')).toContainText(/25[.,]00/);
  await page.keyboard.press('Escape');await expect(detail).not.toBeVisible();await expect(taco).toBeFocused();
  await page.setViewportSize({width:390,height:844});
  await taco.press('Enter');await detail.getByRole('button',{name:'Editar',exact:true}).click();
  const edit=page.getByRole('dialog',{name:'Editar movimiento',exact:true});
  await expect(edit.locator('#descripcion-movimiento')).toHaveValue('Tacos de prueba');
  await expect(edit.locator('#notas')).toHaveValue('Nota separada');
  await edit.locator('#descripcion-movimiento').fill('Tacos con amigos');
  await edit.getByRole('button',{name:'Guardar cambios',exact:true}).click();await expect(edit).not.toBeVisible();
  await expect(cards.filter({hasText:'Tacos con amigos'})).toBeVisible();
  await search.fill('No-existe-123');await expect(page.getByRole('heading',{name:'Sin coincidencias'})).toBeVisible();
  await page.getByRole('button',{name:'Quitar filtros',exact:true}).click();await expect(types.getByRole('button',{name:'Todos',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(search).toHaveValue('');await expect(cards.filter({hasText:'Nomina de prueba'})).toBeVisible();
  await page.getByRole('button',{name:'Abrir filtros avanzados',exact:true}).click();
  const filters=page.getByRole('dialog',{name:'Filtros avanzados'}),minimum=filters.getByRole('spinbutton',{name:'Mín',exact:true});
  await minimum.fill('10');await minimum.focus();await page.setViewportSize({width:390,height:360});
  await expect(filters.getByRole('button',{name:'Aplicar filtros',exact:true})).toBeInViewport();
  await expect.poll(()=>minimum.evaluate(e=>{const r=e.getBoundingClientRect();return r.top>=0 && r.bottom<=innerHeight;})).toBe(true);
  await page.keyboard.press('Escape');await expect(filters).not.toBeVisible();
  await page.setViewportSize({width:320,height:568});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('historial-320.png')});
  await page.locator('.history-tools summary').click();await page.getByRole('button',{name:'Importar CSV',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Importar movimientos desde CSV'})).toBeVisible();
  await expect(page.locator('.history-tools')).not.toHaveAttribute('open','');
  await page.locator('.history-tools summary').click();await page.getByRole('button',{name:'Cerrar importación',exact:true}).click();
  await page.setViewportSize({width:1440,height:900});
  await expect(page.getByRole('table')).toHaveCount(0);
  const desktopCard=cards.filter({hasText:'Tacos con amigos'});
  await expect(desktopCard).toBeVisible();
  await expect(desktopCard).toContainText('Banco de prueba');
  await desktopCard.getByRole('button',{name:'Ver detalle de Tacos con amigos',exact:true}).press('Enter');
  await detail.getByRole('button',{name:'Editar',exact:true}).click();
  await expect(edit).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(edit).not.toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const destino=await page.request.post('/api/cuentas',{headers,data:{nombre:'Ahorro USD',tipo:'DEBITO',moneda:'USD',saldoInicial:0}});
  expect(destino.ok()).toBeTruthy();
  const transferencia=await page.request.post('/api/transacciones',{headers,data:{tipo:'TRANSFERENCIA',monto:25,tasaCambio:0.05,cuentaId,cuentaDestinoId:(await destino.json()).data.id,fecha:localDate(hoy),descripcion:'Ahorro en dólares'}});
  expect(transferencia.ok()).toBeTruthy();
  await page.setViewportSize({width:390,height:844});await types.getByRole('button',{name:'Transferencias',exact:true}).click();
  await expect(cards).toHaveCount(1);await cards.getByRole('button',{name:'Ver detalle de Ahorro en dólares',exact:true}).press('Enter');
  await expect(detail).toContainText('Ahorro USD');
  await expect(detail.getByText('Importe recibido',{exact:true}).locator('..')).toContainText(/1[.,]25/);
  await expect(detail.getByText('Importe recibido',{exact:true}).locator('..')).toContainText('USD');
  await expect(detail.getByText('Tipo de cambio',{exact:true}).locator('..')).toContainText('1 MXN = 0.05 USD');
  await page.screenshot({path:testInfo.outputPath('detalle-transferencia.png')});
  await page.keyboard.press('Escape');await expect(detail).not.toBeVisible();
});
