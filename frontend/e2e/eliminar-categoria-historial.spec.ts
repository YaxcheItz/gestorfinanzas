import { expect, test } from '@playwright/test';
import { registrarPrueba } from './registro-helper';
test('eliminar categoria conserva movimiento historico y respaldo', async ({ page, baseURL }) => {
  expect(['localhost','127.0.0.1']).toContain(new URL(baseURL!).hostname);
  const email=`categoria-${crypto.randomUUID()}@example.test`;
  const registro=await registrarPrueba(page.request,{nombre:'Prueba local',email,password:'Password123'});
  expect(registro.ok()).toBeTruthy(); const headers={Authorization:`Bearer ${(await registro.json()).data.token}`};
  const categoria=await page.request.post('/api/categorias',{headers,data:{nombre:'Origen ficticio',tipo:'GASTO',icono:'shopping-cart',color:'#123456'}});
  expect(categoria.ok()).toBeTruthy(); const origen=(await categoria.json()).data;
  const cuenta=await page.request.post('/api/cuentas',{headers,data:{nombre:'Prueba local',tipo:'DEBITO',moneda:'MXN',saldoInicial:100}});
  expect(cuenta.ok()).toBeTruthy(); const cuentaId=(await cuenta.json()).data.id;
  const movimiento=await page.request.post('/api/transacciones',{headers,data:{cuentaId,categoriaId:origen.id,tipo:'GASTO',monto:10,fecha:'2026-10-01',descripcion:'Ensayo ficticio',etiquetas:['ensayo']}});
  expect(movimiento.ok()).toBeTruthy(); const id=(await movimiento.json()).data.id;
  const eliminado=await page.request.delete(`/api/categorias/${origen.id}`,{headers}); expect(eliminado.ok()).toBeTruthy();
  const despues=await page.request.get(`/api/transacciones/${id}`,{headers}); expect(despues.ok()).toBeTruthy();
  expect((await despues.json()).data.categoriaNombre).toBe(origen.nombre);
  const respaldo=await page.request.get('/api/perfil/respaldo',{headers}); expect(respaldo.ok()).toBeTruthy();
  const copia=await respaldo.json(); const guardado=copia.transacciones.find((t:{id:number})=>t.id===id);
  expect(guardado.categoriaNombre).toBe(origen.nombre);
  const catalogo=await (await page.request.get('/api/categorias/mias',{headers})).json();
  expect(catalogo.data.some((c:{id:number})=>c.id===origen.id)).toBe(false);
  const crear=async(nombre:string)=>{
    const r=await page.request.post('/api/categorias',{headers,data:{nombre,tipo:'GASTO',icono:'car',color:'#123456'}});
    expect(r.ok()).toBeTruthy(); return (await r.json()).data;
  };
  const vigente=await crear('Con presupuesto'),destino=await crear('Nueva clasificacion');
  const partes=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Mexico_City',year:'numeric',month:'numeric'}).formatToParts(new Date());
  const mes=Number(partes.find(p=>p.type==='month')!.value),anio=Number(partes.find(p=>p.type==='year')!.value);
  const presupuesto=await page.request.post('/api/presupuestos',{headers,data:{categoriaId:vigente.id,montoLimite:100,moneda:'MXN',mes,anio}});
  expect(presupuesto.ok()).toBeTruthy();
  await page.goto('/login'); await page.locator('#email').fill(email); await page.locator('#password').fill('Password123');
  await page.getByRole('button',{name:'Iniciar sesi\u00f3n',exact:true}).click(); await expect(page).toHaveURL(/dashboard/);
  await page.goto('/categorias'); await page.getByRole('button',{name:'Eliminar Con presupuesto',exact:true}).click();
  const dialogo=page.getByRole('dialog',{name:'Eliminar Con presupuesto'}); await expect(dialogo).toBeVisible();
  const confirmar=dialogo.getByRole('button',{name:'Confirmar eliminaci\u00f3n'}); await expect(confirmar).toBeDisabled();
  await dialogo.getByLabel('Categor\u00eda de destino').selectOption({label:destino.nombre}); await expect(confirmar).toBeEnabled();
  await page.screenshot({path:'test-results/categoria-eliminacion-confirmacion.png',fullPage:true});
  const eliminacion=page.waitForResponse(r=>r.url().endsWith(`/categorias/${vigente.id}/eliminar`) && r.request().method()==='POST');
  await confirmar.click(); expect((await eliminacion).ok()).toBeTruthy(); await expect(dialogo).toBeHidden();
  const final=await (await page.request.get('/api/perfil/respaldo',{headers})).json();
  expect(final.presupuestos.some((p:{categoriaId:number})=>p.categoriaId===destino.id)).toBe(true);
  await page.goto('/etiquetas'); await page.getByLabel('Nombre de la etiqueta',{exact:true}).fill('ensayo');
  await page.getByRole('button',{name:'A\u00f1adir',exact:true}).click();
  await expect(page.getByText('#ensayo',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/etiquetas-catalogo.png',fullPage:true});
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Eliminar etiqueta ensayo',exact:true}).click();
  await expect(page.getByText('#ensayo',{exact:true})).toHaveCount(0);
  const conservado=await (await page.request.get(`/api/transacciones/${id}`,{headers})).json();
  expect(conservado.data.etiquetas).toEqual(['ensayo']);
});
