CREATE TABLE listas_financieras (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propietario_id bigint REFERENCES usuarios(id) ON DELETE SET NULL,
    nombre varchar(60) NOT NULL,
    emoji varchar(24) NOT NULL DEFAULT '🌿',
    moneda varchar(3) NOT NULL DEFAULT 'MXN',
    clave varchar(12),
    archivada boolean NOT NULL DEFAULT false,
    invitacion_hash varchar(64) UNIQUE,
    invitacion_vence timestamp(6) with time zone,
    invitacion_rol varchar(12),
    CONSTRAINT uk_lista_personal UNIQUE (propietario_id, clave),
    CONSTRAINT ck_lista_moneda CHECK (moneda IN ('MXN','USD','CAD','EUR','GBP'))
);
CREATE TABLE lista_miembros (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lista_id bigint NOT NULL REFERENCES listas_financieras(id) ON DELETE CASCADE,
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    rol varchar(12) NOT NULL CHECK (rol IN ('PROPIETARIO','EDITOR','LECTOR')),
    CONSTRAINT uk_lista_miembro UNIQUE(lista_id, usuario_id)
);
CREATE INDEX idx_lista_miembro_usuario ON lista_miembros(usuario_id, lista_id);
